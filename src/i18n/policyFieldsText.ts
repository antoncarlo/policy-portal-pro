/** Testo italiano di un campo polizza (etichetta, opzione, segnaposto, descrizione) tradotto. */
export const translatePolicyText = (text: string | undefined, language: Language = getLanguage()): string | undefined => {
  if (!text || language === "it") return text;
  return T[text]?.[language] ?? text;
};

export const translatePolicyFieldLabel = (
  _practiceType: string | null | undefined,
  _key: string,
  label: string,
  language: Language = getLanguage(),
) => translatePolicyText(label, language) ?? label;

/** Valore mostrato nel riepilogo: opzioni (anche elenchi separati da virgola) e Sì/No. */
export const translatePolicyFieldValue = (
  _practiceType: string | null | undefined,
  _key: string,
  value: string,
  language: Language = getLanguage(),
) => {
  if (language === "it") return value;
  if (T[value]) return T[value][language];
  if (value.includes(", ")) return value.split(", ").map((part) => T[part]?.[language] ?? part).join(", ");
  return value;
};
